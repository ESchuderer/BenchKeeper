// Writes the build inputs Docusaurus cannot read itself into src/pages/_generated/ (git ignores it; the leading _ keeps it out of the routes), before `docusaurus build`:
// - tokens.css: the design tokens of app/src/tokens.mjs (shared with the app) as Infima variables, light and dark;
// - data.json: the size of each app screenshot, the repository facts for the header, the last commit for the footer;
// - changelog.md and writes.md: Markdown the changelog and writes pages import, with links into the repository made absolute.
import { execFileSync } from 'node:child_process';
import { existsSync, mkdirSync, readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { TOKENS, SHAPE } from '../../app/src/tokens.mjs';

const root = new URL('../../', import.meta.url);
const out = new URL('../src/pages/_generated/', import.meta.url);
export const SLUG = 'ESchuderer/BenchKeeper';
const BLOB = `https://github.com/${SLUG}/blob/main`;

// Infima's primary color needs six shades around it: they are mixed from the token accent, so the site and the app
// share one accent and one source.
export function tokensCss() {
  const SHADES = [['dark', 'black', 90], ['darker', 'black', 85], ['darkest', 'black', 70], ['light', 'white', 90], ['lighter', 'white', 85], ['lightest', 'white', 70]];
  const scheme = (t) => [
    `--ifm-color-primary: ${t.accent};`,
    ...SHADES.map(([s, to, p]) => `--ifm-color-primary-${s}: color-mix(in srgb, ${t.accent} ${p}%, ${to});`),
    `--ifm-background-color: ${t.page};`, `--ifm-background-surface-color: ${t.surface};`,
    `--ifm-font-color-base: ${t.ink};`, `--ifm-font-color-secondary: ${t['ink-2']};`, `--ifm-heading-color: ${t.ink};`,
    `--ifm-toc-border-color: ${t.line};`, `--ifm-hr-background-color: ${t.line};`, `--ifm-table-border-color: ${t.line};`,
    `--ifm-color-emphasis-300: ${t.line};`, `--ifm-card-background-color: ${t.surface};`,
    `--ifm-navbar-background-color: ${t.surface};`, `--ifm-footer-background-color: ${t.surface};`,
    `--ifm-code-background: ${t.grid};`, `--ifm-global-shadow-lw: ${t.shadow};`,
    ...Object.entries(t).map(([k, v]) => `--bk-${k}: ${v};`),
  ].join(' ');
  const shape = `--ifm-global-radius: ${SHAPE['radius-sm']}; --ifm-card-border-radius: ${SHAPE.radius}; --bk-radius: ${SHAPE.radius};
  --ifm-font-family-base: system-ui, -apple-system, "Segoe UI", Roboto, "Helvetica Neue", Arial, sans-serif;
  --ifm-font-family-monospace: ${SHAPE.mono}; --ifm-transition-fast: ${SHAPE.ease};`;
  return `/* Generated by scripts/generate.mjs from app/src/tokens.mjs. */
:root { ${shape} ${scheme(TOKENS.light)} }
html[data-theme='dark'] { ${scheme(TOKENS.dark)} }
`;
}

// The shots are lossless WebP (a VP8L chunk at byte 12): width and height minus one are the two 14-bit fields of the
// little-endian integer at byte 21.
function shots() {
  const dir = new URL('../public/app/', import.meta.url);
  return Object.fromEntries(readdirSync(dir).filter((f) => f.endsWith('.webp')).map((f) => {
    const file = readFileSync(new URL(f, dir));
    if (file.toString('latin1', 12, 16) !== 'VP8L') throw new Error(`${f} is not lossless WebP`);
    const size = file.readUInt32LE(21);
    return [f.slice(0, -'.webp'.length), { width: (size & 0x3fff) + 1, height: ((size >>> 14) & 0x3fff) + 1 }];
  }));
}

// Latest release (or newest tag), stars and forks, read from the GitHub API once per build. Any failure (offline, rate
// limit, timeout) leaves the fact out; the header then shows icon and name only.
async function repoFacts() {
  const get = async (path) => {
    try {
      const token = process.env.GITHUB_TOKEN;
      const r = await fetch(`https://api.github.com/repos/${SLUG}${path}`, {
        headers: { Accept: 'application/vnd.github+json', ...(token ? { Authorization: `Bearer ${token}` } : {}) },
        signal: AbortSignal.timeout(5000),
      });
      return r.ok ? await r.json() : null;
    } catch { return null; }
  };
  const short = (n) => (typeof n !== 'number' ? undefined : n >= 1000 ? `${(n / 1000).toFixed(1).replace(/\.0$/, '')}k` : String(n));
  const [repo, release] = await Promise.all([get(''), get('/releases/latest')]);
  const tags = release?.tag_name ? null : await get('/tags');
  return { tag: release?.tag_name ?? tags?.[0]?.name, stars: short(repo?.stargazers_count), forks: short(repo?.forks_count) };
}

// git from a system folder, as app/test/ui/serve.mjs and .github/scripts/version-pins.mjs run it: no PATH lookup.
const GIT = ['/usr/bin/git', '/usr/local/bin/git', '/opt/homebrew/bin/git'].find((p) => existsSync(p));

// Last commit for the footer; builds without git (e.g. a slim container) omit it.
function lastCommit() {
  if (!GIT) return {};
  try {
    const [updated, commit] = execFileSync(GIT, ['log', '-1', '--format=%cs%n%H'], { encoding: 'utf8' }).trim().split('\n');
    return { updated, commit };
  } catch { return {}; }
}

// Relative links of a Markdown file in the repository point at the file on GitHub.
export const absolute = (md, file) => md.replace(/\]\((?!https?:|#|mailto:)([^)\s]+)\)/g, (_, h) => {
  const u = new URL(h, `https://x/${file}`);
  return `](${BLOB}${u.pathname}${u.search}${u.hash})`;
});

// One `## ` section of a doc, without its heading when bare; a missing section fails the build.
export function section(file, title, bare = false) {
  const text = readFileSync(new URL(file, root), 'utf8');
  const m = new RegExp(`^(## ${title.replace(/[.*+?^${}()|[\]\\]/g, '\\$&')}\\n)([\\s\\S]*?)(?=^## |(?![\\s\\S]))`, 'm').exec(text);
  if (!m) throw new Error(`${file} has no section "## ${title}"`);
  return absolute(bare ? m[2] : m[0], file);
}

// The changelogs, newest component first: each file under its own heading, its entries one level down. The root
// CHANGELOG.md holds the versions up to 6.25; the app and the content release apart from 7.0 on.
export const CHANGELOGS = [
  ['app/CHANGELOG.md', 'App', 'app'],
  ['plugins/benchkeeper/CHANGELOG.md', 'Setup content', 'content'],
  ['CHANGELOG.md', 'Up to 6.25', 'setup'],
];
export function changelog() {
  return CHANGELOGS.filter(([file]) => existsSync(new URL(file, root))).map(([file, title, id]) => {
    const body = readFileSync(new URL(file, root), 'utf8').replace(/^# .*\n/, '').replace(/^(#{2,5}) /gm, '#$1 ');
    return `## ${title} {#${id}}\n\nFrom [${file}](${BLOB}/${file}).\n\n${absolute(body, file)}`;
  }).join('\n');
}

export function writes() {
  return [
    section('docs/setup.md', 'What the app writes and what it never does', true),
    section('docs/security.md', 'Trust boundaries'),
    section('docs/security.md', 'What the app writes'),
    section('docs/security.md', 'What the app never does'),
  ].join('\n');
}

if (import.meta.main) {
  mkdirSync(out, { recursive: true });
  writeFileSync(new URL('tokens.css', out), tokensCss());
  writeFileSync(new URL('data.json', out), `${JSON.stringify({ shots: shots(), repo: await repoFacts(), ...lastCommit() }, null, 2)}\n`);
  writeFileSync(new URL('changelog.md', out), changelog());
  writeFileSync(new URL('writes.md', out), writes());
}
